import os
import logging
import httpx
from typing import Dict, Any

logger = logging.getLogger(__name__)

OLLAMA_URL = os.getenv("OLLAMA_URL", "http://localhost:11434/api/generate")
DEFAULT_OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "llama3.2:1b")


async def query_ollama_with_context(
    question: str,
    context: str,
    model_name: str = DEFAULT_OLLAMA_MODEL
) -> Dict[str, Any]:
    """
    Sends the user question along with grounded database context to Ollama local server.
    Provides graceful fallback if Ollama is not running locally.
    """
    system_prompt = (
        "You are an intelligent data assistant for a Student Database Management System.\n"
        "Answer the user's question accurately using ONLY the grounded database records context provided below.\n"
        "Do not invent false information or reference outside students.\n"
        "Keep your response concise, polite, clear, and professional.\n\n"
        f"--- DATABASE RECORDS CONTEXT ---\n{context}\n---------------------------------"
    )

    prompt_text = f"{system_prompt}\n\nUser Question: {question}\nAnswer:"

    payload = {
        "model": model_name or DEFAULT_OLLAMA_MODEL,
        "prompt": prompt_text,
        "stream": False,
        "options": {
            "temperature": 0.2
        }
    }

    try:
        async with httpx.AsyncClient(timeout=15.0) as client:
            response = await client.post(OLLAMA_URL, json=payload)
            if response.status_code == 200:
                data = response.json()
                answer = data.get("response", "").strip()
                return {
                    "answer": answer or "No response generated by model.",
                    "status": "online",
                    "model_used": model_name
                }
            else:
                logger.warning(f"Ollama returned HTTP status {response.status_code}")
    except Exception as e:
        logger.info(f"Ollama server not reachable at {OLLAMA_URL}: {e}")

    # Fallback smart answer generation based on context when local Ollama is offline
    fallback_answer = generate_contextual_fallback_answer(question, context)
    return {
        "answer": fallback_answer,
        "status": "offline_fallback",
        "model_used": f"{model_name} (Ollama service not running locally; fallback engine active)"
    }


def generate_contextual_fallback_answer(question: str, context: str) -> str:
    """Generate a helpful, grounded fallback answer when local Ollama server is offline."""
    q_lower = question.lower()

    if "how many" in q_lower or "total" in q_lower or "count" in q_lower:
        for line in context.split("\n"):
            if "Total Students:" in line:
                return f"Based on database records: {line.strip()}"
        return "There are currently 0 students recorded in the database."

    if "course" in q_lower or "department" in q_lower or "program" in q_lower:
        for line in context.split("\n"):
            if "Courses Summary:" in line:
                return f"Summary of students per course: {line.replace('Courses Summary:', '').strip()}"

    lines = [line.strip() for line in context.split("\n") if line.startswith("- ID:")]
    if not lines:
        return "The database is currently empty. No student records found."

    matching_lines = []
    # Simple search heuristic for keyword queries like "born after 2005", "John", "Data Science"
    words = [w for w in q_lower.replace("?", "").split() if len(w) > 3]
    for line in lines:
        if any(word in line.lower() for word in words):
            matching_lines.append(line)

    if matching_lines:
        results = "\n".join(matching_lines)
        return (
            f"Here are the relevant student records matching your query:\n{results}\n\n"
            f"(Note: Local Ollama service was offline at {OLLAMA_URL}. To use actual Llama 3.2 models, start 'ollama run llama3.2:1b' locally)."
        )

    return (
        f"Summary of database context:\n{lines[0] if lines else 'No records'}\n\n"
        f"(Total records: {len(lines)}. Note: Ollama service is not running locally at {OLLAMA_URL}. Start Ollama to receive full generative AI responses.)"
    )
